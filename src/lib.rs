/// Derives `CheapClone` by cheaply cloning each field.
///
/// Enable the `derive` feature to use this macro. The type must separately
/// implement `Clone`. All fields must implement `CheapClone`, except fields
/// annotated with `#[cheap_clone(with = "path::to::function")]`.
/// The function receives `&FieldType` and returns `FieldType`; it must preserve
/// the field's value and be cheap to call.
///
/// `#[cheap_clone(inherent)]` also generates a public inherent `cheap_clone`
/// method forwarding to the trait, so callers need not import the trait.
/// `#[cheap_clone(crate = "::renamed_crate")]` overrides the automatically
/// detected crate path (useful for facade re-exports).
///
/// ```
/// #[derive(Clone, cheap_clone::CheapClone)]
/// #[cheap_clone(inherent)]
/// struct Header {
///     id: u64,
///     #[cheap_clone(with = "crate::clone_tag")]
///     tag: Tag,
/// }
///
/// #[derive(Clone, Copy)]
/// struct Tag(u8);
///
/// fn clone_tag(tag: &Tag) -> Tag {
///     *tag
/// }
///
/// # fn main() {
/// let header = Header { id: 42, tag: Tag(1) };
/// let cloned = header.cheap_clone();
/// assert_eq!(cloned.id, 42);
/// assert_eq!(cloned.tag.0, 1);
/// # }
/// ```
///
/// Structs and enums are supported, including generics. Unions and packed
/// representations are not supported. Bounds apply to field types, not all
/// generic parameters; an existing `Clone` implementation can still impose
/// additional bounds.
///
/// A field without `CheapClone` requires an explicit custom function:
///
/// ```compile_fail
/// #[derive(Clone, cheap_clone::CheapClone)]
/// struct Expensive {
///     text: String,
/// }
/// ```
///
/// `Clone` is required and is not generated by this macro:
///
/// ```compile_fail
/// #[derive(cheap_clone::CheapClone)]
/// struct MissingClone(u8);
/// ```
///
/// Custom functions must accept a reference to the field and return its type:
///
/// ```compile_fail
/// #[derive(Clone, cheap_clone::CheapClone)]
/// struct WrongReturn(#[cheap_clone(with = "crate::wrong")] u8);
/// fn wrong(_: &u8) -> u16 { 0 }
/// # fn main() {}
/// ```
///
/// ```compile_fail
/// #[derive(Clone, cheap_clone::CheapClone)]
/// struct WrongArgument(#[cheap_clone(with = "crate::wrong")] u8);
/// fn wrong(value: u8) -> u8 { value }
/// # fn main() {}
/// ```
///
/// Without `inherent`, callers must import the trait or use a qualified call:
///
/// ```compile_fail
/// #[derive(Clone, cheap_clone::CheapClone)]
/// struct Value(u8);
/// let _ = Value(1).cheap_clone();
/// ```
#[cfg(feature = "derive")]
#[cfg_attr(docsrs, doc(cfg(feature = "derive")))]
pub use cheap_clone_derive::CheapClone;

macro_rules! impl_cheap_clone_for_copy {
  ($($ty: ty), +$(,)?) => {
    $(
      impl crate::CheapClone for $ty {
        fn cheap_clone(&self) -> Self {
          *self
        }
      }
    )*
  };
}

/// Things that are fast to clone in the context of an application.
///
/// The purpose of this API is to reduce the number of calls to .clone() which need to
/// be audited for performance.
///
/// As a rule of thumb, only constant-time `Clone` impls should also implement CheapClone.
/// Eg:
/// - ✔ [`Arc<T>`](std::sync::Arc)
/// - ✔ [`Rc<T>`](std::rc::Rc)
/// - ✔ [`Bytes`](bytes_1::Bytes)
/// - ✗ [`Vec<T>`](std::vec::Vec)
/// - ✔ [`SmolStr`](smol_str_0_3::SmolStr)
/// - ✔ [`FastStr`](faststr_0_2::FastStr)
/// - ✗ [`String`]
pub trait CheapClone: Clone {
  /// Returns a copy of the value.
  fn cheap_clone(&self) -> Self {
    self.clone()
  }
}

#[doc(hidden)]
pub mod __private {
  pub use super::CheapClone;
}

