#[cfg(feature = "either_1")]
const _: () = {
  use either_1::Either;

  impl<L: CheapClone, R: CheapClone> CheapClone for Either<L, R> {
    #[inline]
    fn cheap_clone(&self) -> Self {
      match self {
        Either::Left(left) => Either::Left(left.cheap_clone()),
        Either::Right(right) => Either::Right(right.cheap_clone()),
      }
    }
  }
};

